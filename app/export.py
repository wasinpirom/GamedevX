def _story_json(story: dict, assets: dict, prefix_chars: str, prefix_bgs: str, prefix_audio: str) -> dict:
    return {
        "format": "gamedevx-story/1",
        "story": story,
        "assets": {
            "chars": {k: f"{prefix_chars}{k}.png" for k in assets["chars"]},
            "bgs": {k: f"{prefix_bgs}{k}.jpg" for k in assets["bgs"]},
            "music": {k: f"{prefix_audio}{k}{p.suffix}" for k, p in assets["music"].items()},
        },
    }


def export_renpy(pid: int) -> tuple[bytes, str]:
    p = db.load_project(pid)
    story = p["story"]
    assets = collect_assets(pid, story, p["music_map"])
    root = safe_filename(story["title"]) + "_renpy"
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr(f"{root}/game/script.rpy", renpy_script(story, assets))
        z.write(TEMPLATE_DIR / "gamedevx_thai.rpy", f"{root}/game/gamedevx_thai.rpy")
        for f in (TEMPLATE_DIR / "fonts").iterdir():
            z.write(f, f"{root}/game/fonts/{f.name}")
        for k, path in assets["chars"].items():
            z.write(path, f"{root}/game/images/chars/{k}.png")
        for k, path in assets["bgs"].items():
            z.write(path, f"{root}/game/images/bgs/{k}.jpg")
        for k, path in assets["music"].items():
            z.write(path, f"{root}/game/audio/{k}{path.suffix}")
        z.writestr(f"{root}/story.json", json.dumps(
            _story_json(story, assets, "game/images/chars/", "game/images/bgs/", "game/audio/"),
            ensure_ascii=False, indent=2))
        z.writestr(f"{root}/README_TH.txt", README_RENPY.format(title=story["title"], line=config.LINE_OA_ID))
    return buf.getvalue(), f"{root}.zip"


