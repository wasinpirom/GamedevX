"""Exporters: Ren'Py project, standalone web game, and a raw asset pack.

All exports contain real asset files (PNG/JPG/audio) plus story.json, so the work
can be moved to any engine — not just code that draws shapes.
"""
import io
import json
import re
import zipfile
from pathlib import Path

from . import config, db, pipeline

TEMPLATE_DIR = Path(__file__).parent / "renpy_template"
STATIC_DIR = Path(__file__).parent / "static"

try:
    from pythainlp.tokenize import word_tokenize as _thai_tokenize
except Exception:  # pragma: no cover
    _thai_tokenize = None

_THAI = re.compile(r"[฀-๿]+")
ZWSP = "​"


def thai_breaks(text: str) -> str:
    """Insert zero-width spaces between Thai words so Ren'Py can wrap lines correctly."""
    if not _thai_tokenize or not _THAI.search(text):
        return text

    def seg(m: re.Match) -> str:
        try:
            return ZWSP.join(_thai_tokenize(m.group(0), engine="newmm", keep_whitespace=True))
        except Exception:  # noqa: BLE001
            return m.group(0)

    return _THAI.sub(seg, text)


def rpy_str(text: str) -> str:
    """Escape text for a Ren'Py double-quoted string."""
    t = thai_breaks(str(text)).replace("\\", "\\\\").replace('"', '\\"')
    t = t.replace("[", "[[").replace("{", "{{").replace("\n", "\\n")
    return f'"{t}"'


def safe_filename(s: str) -> str:
    s = re.sub(r"[^\w\u0E00-\u0E7F\-]+", "_", s).strip("_")
    return s[:50] or "game"


def _positions(n: int) -> list[str]:
    return {1: ["center"], 2: ["left", "right"], 3: ["left", "center", "right"]}.get(
        n, ["left", "center", "right"] * 3)


def collect_assets(pid: int, story: dict, music_map: dict) -> dict:
    """Map of asset key -> local Path for everything that exists."""
    chars, bgs, music = {}, {}, {}
    for c in story["characters"]:
        for e in pipeline.used_expressions(story, c["id"]):
            p = pipeline.char_path(pid, c["id"], e)
            if p.exists():
                chars[f"{c['id']}_{e}"] = p
    for b in story["backgrounds"]:
        p = pipeline.bg_path(pid, b["id"])
        if p.exists():
            bgs[b["id"]] = p
    for mood in pipeline.used_moods(story):
        f = pipeline.music_file(pid, music_map.get(mood))
        if f:
            music[mood] = f
    return {"chars": chars, "bgs": bgs, "music": music}


# ============================================================ Ren'Py
def renpy_script(story: dict, assets: dict) -> str:
    L = []
    w = L.append
    w("# ============================================================")
    w(f"# {story['title']}")
    w("# Generated by GamedevX (gamedevx.com) - edit freely!")
    w("# ============================================================")
    w("")
    for c in story["characters"]:
        w(f"define ch_{c['id']} = Character({rpy_str(c['name'])}, color=\"{c['color']}\")")
    w("")
    w("# ---- character sprites ----")
    for c in story["characters"]:
        for e in pipeline.used_expressions(story, c["id"]):
            key = f"{c['id']}_{e}"
            if key in assets["chars"]:
                w(f"image ch_{c['id']} {e} = \"images/chars/{key}.png\"")
            else:
                w(f"image ch_{c['id']} {e} = Fixed(Solid(\"{c['color']}88\", xysize=(420, 900)), "
                  f"Text({rpy_str(c['name'] + ' (' + e + ')')}, align=(0.5, 0.5)), "
                  f"xysize=(420, 900))  # TODO: no image yet")
    w("")
    w("# ---- backgrounds ----")
    for b in story["backgrounds"]:
        if b["id"] in assets["bgs"]:
            w(f"image bg {b['id']} = \"images/bgs/{b['id']}.jpg\"")
        else:
            w(f"image bg {b['id']} = Solid(\"#2b2d42\")  # TODO: no image yet")
    w("")
    w("label start:")
    w(f"    jump sc_{story['scenes'][0]['id']}")
    w("")
    for s in story["scenes"]:
        w(f"label sc_{s['id']}:")
        w(f"    # {s['title']}")
        w(f"    scene bg {s['bg']} with fade" if s.get("bg") else "    scene black with fade")
        if s["mood"] in assets["music"]:
            ext = assets["music"][s["mood"]].suffix
            w(f"    play music \"audio/{s['mood']}{ext}\" fadein 1.0 if_changed")
        speakers = []
        for ln in s["lines"]:
            if ln["t"] == "say" and ln["who"] not in speakers:
                speakers.append(ln["who"])
        pos = dict(zip(speakers, _positions(len(speakers))))
        shown: dict[str, str] = {}
        ended = False
        for ln in s["lines"]:
            t = ln["t"]
            if t == "narr":
                w(f"    {rpy_str(ln['text'])}")
            elif t == "say":
                if shown.get(ln["who"]) != ln["expr"]:
                    trans = " with dissolve" if ln["who"] not in shown else ""
                    w(f"    show ch_{ln['who']} {ln['expr']} at {pos[ln['who']]}{trans}")
                    shown[ln["who"]] = ln["expr"]
                w(f"    ch_{ln['who']} {rpy_str(ln['text'])}")
            elif t == "choice":
                w("    menu:")
                for o in ln["options"]:
                    w(f"        {rpy_str(o['text'])}:")
                    w(f"            jump sc_{o['goto']}" if o.get("goto") else "            return")
                ended = True
            elif t == "goto":
                w(f"    jump sc_{ln['scene']}")
                ended = True
            elif t == "end":
                w("    \"— จบ —\"" if re.search(r"[฀-๿]", story["title"] + story["synopsis"])
                  else "    \"— THE END —\"")
                w("    return")
                ended = True
            if ended:
                break
        if not s["lines"]:
            w("    pass")
        w("")
    return "\n".join(L)


