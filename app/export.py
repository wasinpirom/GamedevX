def export_web(pid: int) -> tuple[bytes, str]:
    p = db.load_project(pid)
    story = p["story"]
    assets = collect_assets(pid, story, p["music_map"])
    root = safe_filename(story["title"]) + "_web"
    data = _story_json(story, assets, "assets/chars/", "assets/bgs/", "assets/audio/")
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr(f"{root}/index.html", WEB_INDEX.format(title=story["title"].replace("<", "&lt;")))
        z.write(STATIC_DIR / "js" / "player.js", f"{root}/player.js")
