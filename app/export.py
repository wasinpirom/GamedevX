# ============================================================ Asset pack
def export_assets(pid: int) -> tuple[bytes, str]:
    p = db.load_project(pid)
    story = p["story"]
    assets = collect_assets(pid, story, p["music_map"])
    root = safe_filename(story["title"]) + "_assets"
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for k, path in assets["chars"].items():
            z.write(path, f"{root}/characters/{k}.png")
        for k, path in assets["bgs"].items():
            z.write(path, f"{root}/backgrounds/{k}.jpg")
        for k, path in assets["music"].items():
            z.write(path, f"{root}/music/{k}{path.suffix}")
        z.writestr(f"{root}/story.json", json.dumps(
            _story_json(story, assets, "characters/", "backgrounds/", "music/"), ensure_ascii=False, indent=2))
        z.writestr(f"{root}/README_TH.txt",
                   "ชุด asset จาก GamedevX\n\n"
                   "- characters/  ภาพตัวละคร PNG พื้นหลังใส สูง 1000px ชื่อไฟล์ = <ตัวละคร>_<สีหน้า>.png\n"
                   "- backgrounds/ ภาพฉากหลัง JPG 1920x1080\n"
                   "- music/       เพลงประกอบตามอารมณ์ฉาก\n"
                   "- story.json   บทเกมทั้งหมด (ตัวละคร ฉาก บทพูด ตัวเลือก) ใช้กับ Unity / Godot / pygame ได้\n")
    return buf.getvalue(), f"{root}.zip"
