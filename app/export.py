        for k, path in assets["chars"].items():
            z.write(path, f"{root}/assets/chars/{k}.png")
        for k, path in assets["bgs"].items():
            z.write(path, f"{root}/assets/bgs/{k}.jpg")
        for k, path in assets["music"].items():
            z.write(path, f"{root}/assets/audio/{k}{path.suffix}")
